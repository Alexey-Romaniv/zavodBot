def shift_when(moment, start) -> str:
    """«Через ~2 ч.» или «Завтра» — вечернее напоминание не должно писать «через 9 часов»."""
    if start.date() > moment.date():
        return "Завтра"
    hours = max(1, round((start - moment).total_seconds() / 3600))
    return f"Через ~{hours} ч."


